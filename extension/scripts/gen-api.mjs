// Generates src/models/api.d.ts from the backend's OpenAPI schema so the extension's types
// cannot drift from the API. `--check` regenerates in memory and fails if files are stale.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const repo = resolve(root, '..');
const schemaPath = join(root, 'src', 'models', 'openapi.json');
const typesPath = join(root, 'src', 'models', 'api.d.ts');
const check = process.argv.includes('--check');

function findPython() {
  const candidates = [
    process.env.SS_PYTHON,
    join(repo, '.venv', 'Scripts', 'python.exe'),
    join(repo, '.venv', 'bin', 'python3'),
    join(repo, '.venv', 'bin', 'python'),
    'python3',
    'python',
  ].filter(Boolean);
  return candidates.find((c) => c === 'python' || c === 'python3' || existsSync(c));
}

function exportSchema(target) {
  const python = findPython();
  try {
    execFileSync(python, [join(repo, 'scripts', 'export_openapi.py'), target], { stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (err) {
    console.error(`Could not export the backend schema with ${python}.`);
    console.error('Set SS_PYTHON to a Python that has backend/requirements.txt installed.');
    console.error(String(err.stderr ?? err.message).split('\n').slice(-6).join('\n'));
    process.exit(1);
  }
}

async function render(schemaFile) {
  const ast = await openapiTS(pathToFileURL(schemaFile));
  return `// GENERATED by scripts/gen-api.mjs from the backend OpenAPI schema. Do not edit.\n${astToString(ast)}`;
}

const tmp = mkdtempSync(join(tmpdir(), 'ss-api-'));
try {
  const freshSchema = join(tmp, 'openapi.json');
  exportSchema(freshSchema);
  const freshTypes = await render(freshSchema);

  if (check) {
    const stale =
      !existsSync(schemaPath) ||
      !existsSync(typesPath) ||
      readFileSync(schemaPath, 'utf8') !== readFileSync(freshSchema, 'utf8') ||
      readFileSync(typesPath, 'utf8') !== freshTypes;
    if (stale) {
      console.error('API types are stale. Run `npm run gen:api` and commit the result.');
      process.exit(1);
    }
    console.log('API types are up to date.');
  } else {
    writeFileSync(schemaPath, readFileSync(freshSchema));
    writeFileSync(typesPath, freshTypes);
    console.log(`wrote ${typesPath}`);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
